"""Render the native current-policy layouts without importing a GPU backend."""

import argparse
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "src/druta/power_layout_catalog.py"
HEADER = ROOT / "native/src/backend/power_layout_catalog_generated.h"


def values(items):
    return ", ".join(map(str, items))


def initializer(key, row, commands):
    fields = {"sizes", "commands", "info", "status", "control", "status_mask_word", "control_mask_word"}
    if row.keys() - fields:
        raise ValueError(f"Unrepresented fields on {key}: {row.keys() - fields}")
    if tuple(row["sizes"]) != commands or ("commands" in row and tuple(row["commands"]) != commands):
        raise ValueError(f"Inconsistent command slots on {key}")
    if any(len(row[field]) != 2 for field in ("info", "status", "control")):
        raise ValueError(f"Expected a base and stride for each record on {key}")
    sizes = values(row["sizes"].values())
    mapping = row.get("commands")
    native_commands = values(f"0x{value:08X}" for value in mapping.values()) if mapping else "0, 0, 0, 0"
    geometry = values((*row["info"], *row["status"], *row["control"]))
    masks = values(row.get(field, "std::nullopt") for field in ("status_mask_word", "control_mask_word"))
    command, packet, parameter = key
    return (f"    {{{{0x{command:08X}, {packet}, {parameter}}},\n"
            f"     {{{{{sizes}}}, {'true' if mapping else 'false'}, {{{native_commands}}},\n"
            f"      {geometry}, {masks}}}}},\n")


def render():
    catalog = runpy.run_path(str(CATALOG))
    primary = catalog["CURRENT_LIMIT_LAYOUTS"]
    fallbacks = catalog["CURRENT_LIMIT_LAYOUT_FALLBACKS"]
    if fallbacks.keys() - primary.keys():
        raise ValueError("A fallback needs a primary layout with the same transport key")
    commands = tuple(next(iter(primary.values()))["sizes"])
    rows = [initializer(key, row, commands) for key, row in primary.items()]
    # Preserve the native full-table selector scan order. Within each key both
    # backends use the primary first and then the fallbacks in catalog order.
    for key in sorted(fallbacks, reverse=True):
        rows.extend(initializer(key, row, commands) for row in fallbacks[key])
    checks = f"static_assert(sizeof(kPowerGetCommands) / sizeof(kPowerGetCommands[0]) == {len(commands)});\n"
    checks += "".join(f"static_assert(kPowerGetCommands[{i}] == 0x{command:08X});\n"
                      for i, command in enumerate(commands))
    return ("""// Druta - a monitor and tuner for NVIDIA GPUs.
// Copyright (C) 2026 Thermetery Technology Co Limited
// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by native/tools/generate_power_layouts.py from src/druta/power_layout_catalog.py.
#pragma once

#include "backend/power_layouts.h"

namespace druta::backend::catalog {

struct KeyedLayout {
    PowerLayoutKey key;
    PowerLayout layout;
};

""" + checks + "\ninline constexpr KeyedLayout kPowerLayouts[] = {\n" +
            "".join(rows) + "};\n\n}  // namespace druta::backend::catalog\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in header differs")
    expected = render()
    if parser.parse_args().check:
        if not HEADER.is_file() or HEADER.read_text(encoding="utf-8") != expected:
            raise SystemExit("Regenerate the stale native header with python native/tools/generate_power_layouts.py")
    else:
        HEADER.write_text(expected, encoding="utf-8", newline="\n")
